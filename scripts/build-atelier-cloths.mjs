#!/usr/bin/env node
/**
 * Regenerate convex/shared/atelier/cloths.ts from research/nyoni/atelier-cloths.json.
 *
 *   node scripts/build-atelier-cloths.mjs
 *
 * The JSON is the curated list (by WooCommerce slug) of the house's bespoke cloths with the mill-book
 * photographs the store publishes; fetch those with scripts/fetch-atelier-cloth-images.mjs first.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const SOURCE = path.resolve("research/nyoni/atelier-cloths.json");
const TARGET = path.resolve("convex/shared/atelier/cloths.ts");

const WEIGHT = {
  "four-season": "four_season",
  "autumn-winter": "autumn_winter",
  lightweight: "lightweight",
  summer: "summer",
};
const PATTERN = {
  solid: "solid",
  pinstripe: "pinstripe",
  "chalk stripe": "chalk_stripe",
  "glen check": "glen_check",
  plaid: "plaid",
  jacquard: "jacquard",
  herringbone: "herringbone",
};
const OCCASION = {
  wedding: "wedding",
  business: "business",
  "black-tie": "black_tie",
  corporate: "corporate",
  "casual-refinement": "casual_refinement",
};

const { cloths, source } = JSON.parse(await readFile(SOURCE, "utf8"));
const rows = cloths.map((c, index) => ({
  code: c.code,
  name: c.name,
  mill: c.mill,
  storeName: c.storeName,
  supplierRef: c.storeName,
  productUrl: c.productUrl,
  productId: c.productId,
  description: c.note,
  composition: c.composition,
  weight: WEIGHT[c.weight] ?? "four_season",
  pattern: PATTERN[c.pattern] ?? "solid",
  colour: c.colour,
  hex: c.hex,
  season: c.season,
  occasions: c.occasions.map((o) => OCCASION[o] ?? o),
  priceUsd: c.priceUsd ?? undefined,
  inStock: c.inStock,
  image: c.localImage,
  sortOrder: index,
}));

const body = rows
  .map((r) => {
    const fields = Object.entries(r)
      .filter(([, v]) => v !== undefined)
      .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
      .join("\n");
    return `  {\n${fields}\n  },`;
  })
  .join("\n");

const file = `import type { ClothPattern, ClothWeight, Occasion } from "./enums";
import type { Season } from "../wardrobe";

/**
 * The house's bespoke cloths as sold on nyonicouture.com. GENERATED by scripts/build-atelier-cloths.mjs
 * from research/nyoni/atelier-cloths.json (${source}); edit the JSON, not this file.
 *
 * The store photographs the mill books, not flat swatches, so \`image\` is the book and \`hex\` is a
 * representative shade for the studio figure. Entries are seeded with \`shadeConfirmed: false\` until a
 * fitter confirms the shade against the real cloth (journey O02).
 */
export type ClothSeed = {
  code: string;
  name: string;
  mill: string;
  /** The product title as the store lists it; the supplier reference staff quote to the mill. */
  storeName: string;
  supplierRef: string;
  productUrl: string;
  productId: number;
  description: string;
  composition: string;
  weight: ClothWeight;
  pattern: ClothPattern;
  colour: string;
  hex: string;
  season: Season[];
  occasions: Occasion[];
  /** The commission price the store lists for a suit in this cloth, when it lists one. */
  priceUsd?: number;
  inStock: boolean;
  /** Path under public/ to the photograph of the mill book. */
  image: string;
  sortOrder: number;
};

export const CLOTH_SEED: readonly ClothSeed[] = [
${body}
];

export function clothSeedByCode(code: string): ClothSeed | undefined {
  return CLOTH_SEED.find((cloth) => cloth.code === code);
}
`;
await writeFile(TARGET, file);
console.log(`${rows.length} cloths written to ${path.relative(process.cwd(), TARGET)}`);
